	@Override
	public void fillDate(Date tuNgay, Date denNgay) {
		List<DoanhThu> rss = dao.DoanhThuTheoNgay(tuNgay, denNgay);
		fillToTable(rss);
	}

	@Override
	public void findbyTime(String ngay) {
		SimpleDateFormat sdf = new SimpleDateFormat("yyyy-MM-dd");
		Date date = null;
		try {
			date = sdf.parse(ngay);
		} catch (ParseException ex) {
			Logger.getLogger(DoanhThuFrame.class.getName()).log(Level.SEVERE, null, ex);
		}
		if (ngay == null || ngay.isEmpty()) {

			return;
		}
		DoanhThu hd = dao.findbyTime(date);
		List<DoanhThu> rs = new ArrayList<>();
		if (hd != null) {
			rs.add(hd);
		}
		fillToTable(rs);
	}

	@Override
	public void open() {
		this.setLocationRelativeTo(null);
		load();
	}

	@Override
	public void fillToTable(List<DoanhThu> list) {
		DefaultTableModel model = (DefaultTableModel) tblDoanhThu.getModel();
		model.setRowCount(0);
		list.forEach(item -> {
			Object[] rowData = { item.getNgay(), item.getSoHoaDon(), item.getSoSanPham(), item.getTongTien(), false };
			model.addRow(rowData);
		});
	}

	@Override
	public void load() {
		items = dao.findAll();
		fillToTable(items);
	}
