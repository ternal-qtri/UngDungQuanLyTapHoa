	private void cboNgayActionPerformed(java.awt.event.ActionEvent evt) {

		String selected = cboNgay.getSelectedItem().toString();// lấy giá trị trên cbo
		LocalDate today = LocalDate.now();
		DateTimeFormatter fmt = DateTimeFormatter.ofPattern("yyyy-MM-dd");

		if (selected.equals("Hôm nay")) {
			String dateStr = today.format(fmt);
			txtTuNgay.setText(dateStr);
			txtDenNgay.setText(dateStr);

		} else if (selected.equals("Tuần này")) {
			LocalDate start = today.with(DayOfWeek.MONDAY);// trả về ngày thứ 2 gần nhất today
			LocalDate end = today.with(DayOfWeek.SUNDAY);
			txtTuNgay.setText(start.format(fmt));
			txtDenNgay.setText(end.format(fmt));

		} else if (selected.equals("Tháng này")) {
			LocalDate start = today.withDayOfMonth(1);
			LocalDate end = today.withDayOfMonth(today.lengthOfMonth());
			txtTuNgay.setText(start.format(fmt));
			txtDenNgay.setText(end.format(fmt));

		} else if (selected.equals("Năm nay")) {
			LocalDate start = LocalDate.of(today.getYear(), 1, 1);
			LocalDate end = LocalDate.of(today.getYear(), 12, 31);
			txtTuNgay.setText(start.format(fmt));
			txtDenNgay.setText(end.format(fmt));
		}
	}

